export function getSyntheticResearchProfile(profileId) {
  if (profileId === 'complete_synthetic') {
    return {
      profileId,
      profileLabel: 'Complete synthetic example (40 of 40 features)',
      profileDescription: 'Fictional values generated by the server for a software demonstration only.',
      features: { ...COMPLETE_SYNTHETIC_FEATURES },
    };
  }
  if (profileId === 'incomplete_synthetic') {
    return {
      profileId,
      profileLabel: 'Intentionally incomplete example (7 of 40 features)',
      profileDescription: 'Demonstrates the API withholding a score when too many model features are missing.',
      features: { ...INCOMPLETE_SYNTHETIC_FEATURES },
    };
  }
  throw new ResearchModelServiceError('Choose one of the approved synthetic demo profiles.', 'research_model_invalid_demo_profile');
}

export function isXGBoostResearchServiceConfigured(env = process.env) {
  const url = String(env.BEDALLOCATION_XGBOOST_SERVICE_URL || '').trim();
  const key = String(env.BEDALLOCATION_XGBOOST_API_KEY || env.BEDALLOCATION_ML_API_KEY || '').trim();
  if (!url || key.length < 32) return false;
  try {
    getResearchModelServiceConfig({
      ...env,
      BEDALLOCATION_ML_SERVICE_URL: url,
      BEDALLOCATION_ML_API_KEY: key,
    });
    return true;
  } catch {
    return false;
  }
}

function configForModel(modelKey, env) {
  if (modelKey === 'hist_gradient_boosting') return getResearchModelServiceConfig(env);
  if (modelKey === 'xgboost_hist_weighted') {
    const url = String(env.BEDALLOCATION_XGBOOST_SERVICE_URL || '').trim();
    const apiKey = String(env.BEDALLOCATION_XGBOOST_API_KEY || env.BEDALLOCATION_ML_API_KEY || '').trim();
    if (!url || apiKey.length < 32) {
      throw new ResearchModelServiceError(
        'The optional XGBoost research service is not configured.',
        'research_model_comparison_not_configured',
      );
    }
    return getResearchModelServiceConfig({
      ...env,
      BEDALLOCATION_ML_SERVICE_URL: url,
      BEDALLOCATION_ML_API_KEY: apiKey,
    });
  }
  throw new ResearchModelServiceError('Requested research model is not supported.', 'research_model_not_supported');
}

async function requestJson(fetchImpl, url, options, unavailableMessage) {
  let response;
  try {
    response = await fetchImpl(url, {
      ...options,
      cache: 'no-store',
      redirect: 'error',
      signal: AbortSignal.timeout(MAX_TIMEOUT_MS),
    });
  } catch {
    throw new ResearchModelServiceError(unavailableMessage);
  }
  if (!response.ok) throw new ResearchModelServiceError(unavailableMessage);
  try {
    return await response.json();
  } catch {
    throw new ResearchModelServiceError('Research model service returned invalid JSON.');
  }
}

function normalizePrediction(payload, modelKey, profile) {
  if (!payload || typeof payload !== 'object' || Array.isArray(payload)) {
    throw new ResearchModelServiceError('Research model returned an invalid prediction response.');
  }
  if (payload.model_key !== modelKey || payload.target_column !== EXPECTED_TARGET
      || payload.score_type !== 'uncalibrated_model_score'
      || payload.persisted !== false
      || payload.changes_patient_record !== false
      || payload.changes_queue_or_bed_status !== false) {
    throw new ResearchModelServiceError('Research prediction metadata did not match the expected read-only contract.');
  }
  const scoreStatus = payload.score_status;
  const score = payload.score;
  if (!['available', 'withheld'].includes(scoreStatus)
      || (scoreStatus === 'available' && (typeof score !== 'number' || !Number.isFinite(score) || score < 0 || score > 1))
      || (scoreStatus === 'withheld' && score !== null)) {
    throw new ResearchModelServiceError('Research model returned an invalid score status.');
  }
  if (!Number.isInteger(payload.expected_feature_count) || payload.expected_feature_count !== 40
      || !Number.isInteger(payload.supplied_non_missing_feature_count)
      || payload.supplied_non_missing_feature_count < 0 || payload.supplied_non_missing_feature_count > 40
      || !Number.isInteger(payload.missing_feature_count) || payload.missing_feature_count < 0
      || !Array.isArray(payload.missing_features)) {
    throw new ResearchModelServiceError('Research model returned invalid feature-completeness metadata.');
  }
  return {
    modelKey,
    modelVersion: String(payload.model_version || 'unknown'),
    targetColumn: payload.target_column,
    targetDefinition: String(payload.target_definition || ''),
    score,
    scoreStatus,
    withheldReason: typeof payload.withheld_reason === 'string' ? payload.withheld_reason : null,
    scoreType: payload.score_type,
    expectedFeatureCount: payload.expected_feature_count,
    suppliedNonMissingFeatureCount: payload.supplied_non_missing_feature_count,
    missingFeatureCount: payload.missing_feature_count,
    missingFeatures: payload.missing_features.filter((name) => typeof name === 'string').slice(0, 40),
    featureCompletenessFraction: Number(payload.feature_completeness_fraction) || 0,
    lowFeatureCompleteness: Boolean(payload.low_feature_completeness),
    profileId: profile.profileId,
    profileLabel: profile.profileLabel,
    syntheticInput: true,
    persisted: false,
    changesPatientRecord: false,
    changesQueueOrBedStatus: false,
    clinicalLimitations: Array.isArray(payload.clinical_limitations)
      ? payload.clinical_limitations.filter((item) => typeof item === 'string').slice(0, 10)
      : [],
  };
}

export async function fetchSyntheticResearchPrediction({
  modelKey,
  profileId,
  env = process.env,
  fetchImpl = globalThis.fetch,
} = {}) {
  if (typeof fetchImpl !== 'function') throw new ResearchModelServiceError('Server fetch API is unavailable.');
  if (!PROFILE_IDS.has(profileId)) {
    throw new ResearchModelServiceError('Choose one of the approved synthetic demo profiles.', 'research_model_invalid_demo_profile');
  }
  const profile = getSyntheticResearchProfile(profileId);
  const config = configForModel(modelKey, env);
  const headers = { 'X-API-Key': config.apiKey, Accept: 'application/json' };
  const info = await requestJson(
    fetchImpl,
    `${config.baseUrl}/v1/model-info`,
    { method: 'GET', headers },
    'Research model service could not be reached or did not return model metadata.',
  );
  const normalizedInfo = validateResearchModelInfo(info);
  if (normalizedInfo.modelKey !== modelKey) {
    throw new ResearchModelServiceError('Configured research endpoint is serving a different model than requested.');
  }
  const rawPrediction = await requestJson(
    fetchImpl,
    `${config.baseUrl}/v1/predict`,
    {
      method: 'POST',
      headers: { ...headers, 'Content-Type': 'application/json' },
      body: JSON.stringify({ features: profile.features }),
    },
    'Research model prediction failed or the service is unavailable.',
  );
  return normalizePrediction(rawPrediction, modelKey, profile);
}

export async function runSyntheticResearchDemo({
  profileId,
  compareModels = false,
  env = process.env,
  fetchImpl = globalThis.fetch,
} = {}) {
  const modelKeys = compareModels
    ? ['hist_gradient_boosting', 'xgboost_hist_weighted']
    : ['hist_gradient_boosting'];
  const results = await Promise.all(modelKeys.map(async (modelKey) => {
    try {
      const result = await fetchSyntheticResearchPrediction({ modelKey, profileId, env, fetchImpl });
      return { modelKey, status: 'available', ...result };
    } catch (error) {
      const code = error instanceof ResearchModelServiceError ? error.code : 'research_model_unavailable';
      return {
        modelKey,
        status: 'unavailable',
        errorCode: code,
        error: modelKey === 'xgboost_hist_weighted'
          ? 'XGBoost comparison service is unavailable or not configured.'
          : 'Histogram Gradient Boosting research service is unavailable.',
        syntheticInput: true,
        persisted: false,
        changesPatientRecord: false,
        changesQueueOrBedStatus: false,
      };
    }
  }));

  const primary = results.find((result) => result.modelKey === 'hist_gradient_boosting');
  if (!primary || primary.status !== 'available') {
    throw new ResearchModelServiceError(
      primary?.error || 'Primary research model is unavailable.',
      primary?.errorCode || 'research_model_unavailable',
    );
  }

  return {
    profileId,
    profileLabel: getSyntheticResearchProfile(profileId).profileLabel,
    syntheticOnly: true,
    persisted: false,
    changesPatientRecord: false,
    changesQueueOrBedStatus: false,
    comparisonRequested: Boolean(compareModels),
    comparisonNote: compareModels
      ? 'Scores are uncalibrated outputs from separate research models and must not be interpreted as comparable clinical probabilities.'
      : 'This is a synthetic software demonstration, not a patient assessment.',
    results,
  };
}
